#!/usr/bin/env python3
"""Render Arcana's command families as Claude Code plugins under plugins/.

Claude Code installs Arcana from the repository's own marketplace
(`.claude-plugin/marketplace.json`): one plugin per command family, `grm` and
`arc`. Each plugin is a thin carrier: its skills are rendered from the same
`skills/<family>/<slug>/SKILL.md` sources the flat registration uses, with
every invocation inlined, so a plugin skill is self-contained and runs the
engine at its one location, `~/grimoires/arcana`. The `grm` plugin also
carries the session-start hook (`hooks/`, `scripts/`), which is authored in
place and left untouched by this rite.

The rendered tree is committed: a marketplace serves it straight from git.
This rite regenerates it; `--check` reports drift between the sources and the
committed render, and the test suite runs that check.

Usage:
    python3 rites/build_plugins.py            # report drift (exit 1 when stale)
    python3 rites/build_plugins.py --apply    # write plugins/<family>/...

Exit codes: 0 = in sync or written, 1 = drift found (without --apply),
2 = argparse invalid arguments.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import sync_skills
from _lib import SKILL_PREFIX_PLACEHOLDER
from diagnostics import ResultReporter, add_output_format_arg

ARCANA_PATH = Path(__file__).resolve().parent.parent
PLUGINS_DIR = ARCANA_PATH / "plugins"
ENGINE_HOME = "~/grimoires/arcana"
GENERATED_COMMENT = (
    "<!-- GENERATED by rites/build_plugins.py from {source} - do not edit; "
    "edit the source and run python rites/build_plugins.py --apply -->"
)
PLUGIN_DESCRIPTIONS = {
    "grm": "Grimoire: the nine grimoire verbs (setup, create, add, save, update, check, move, remove, help) plus the session-start routing hook.",
    "arc": "Arcana maintainer verbs (update, validate, improve, clean, help) for people who maintain the engine itself.",
}
NAME_RE = re.compile(r"^name:\s*.*$", re.MULTILINE)


def version() -> str:
    return (ARCANA_PATH / "VERSION").read_text(encoding="utf-8").strip()


def render_plugin_skill(spec: sync_skills.SkillSpec) -> str:
    """Render one source skill for the plugin: slug name, engine at its home path."""
    source = spec.source_dir / "SKILL.md"
    real_root = ARCANA_PATH.as_posix()

    def substitute(text: str) -> str:
        # Resolve against the real checkout so directives inline; the engine
        # home replaces the real path once the text is assembled.
        text = text.replace(SKILL_PREFIX_PLACEHOLDER, spec.skill_prefix)
        text = text.replace("{{ARCANA_PATH}}", real_root)
        text = text.replace("ARCANA_HOME/", f"{real_root}/")
        return text

    content = substitute(source.read_text(encoding="utf-8"))
    content = sync_skills.inline_dynamic_context(content, source, substitute)
    content = content.replace(real_root, ENGINE_HOME)
    # Claude Code names a plugin skill /<plugin>:<name>; the family prefix is
    # the plugin, so the skill keeps only its slug.
    content = NAME_RE.sub(f"name: {spec.command_slug}", content, count=1)
    comment = GENERATED_COMMENT.format(source=source.relative_to(ARCANA_PATH).as_posix())
    if content.startswith("---\n"):
        end = content.find("\n---", 4)
        if end != -1:
            insert_at = end + len("\n---")
            return content[:insert_at] + f"\n{comment}\n" + content[insert_at:]
    return f"{comment}\n{content}"


def render_family(family: dict) -> dict[str, str]:
    """Return {relative path: content} for one family's plugin tree."""
    files: dict[str, str] = {}
    manifest = {
        "name": family["skill_prefix"],
        "version": version(),
        "description": PLUGIN_DESCRIPTIONS.get(family["skill_prefix"], f"Arcana {family['name']} commands"),
        "author": {"name": "Justin Lavi", "url": "https://github.com/justinlavi/arcana"},
        "homepage": "https://github.com/justinlavi/arcana",
        "repository": "https://github.com/justinlavi/arcana",
        "license": "MIT",
    }
    files[".claude-plugin/plugin.json"] = json.dumps(manifest, indent=2) + "\n"
    specs = [spec for spec in sync_skills.collect_arcana_skill_specs() if spec.source_key == family["name"]]
    for spec in specs:
        files[f"skills/{spec.command_slug}/SKILL.md"] = render_plugin_skill(spec)
    if family["skill_prefix"] == "grm":
        # The hook prints the routing block before the engine exists, so the
        # plugin carries a copy of the canonical template.
        template = ARCANA_PATH / "rites" / "templates" / "grimoire_block.md"
        files["scripts/grimoire_block.md"] = template.read_text(encoding="utf-8")
    return files


def render_all() -> dict[str, str]:
    """Return {path relative to plugins/: content} for every family."""
    rendered: dict[str, str] = {}
    for family in sync_skills.load_arcana_skill_families():
        prefix = family["skill_prefix"]
        for rel, content in render_family(family).items():
            rendered[f"{prefix}/{rel}"] = content
    return rendered


def current_render_targets() -> dict[str, str]:
    """The committed files this rite owns (plugin.json and skills); hooks and scripts are authored."""
    existing: dict[str, str] = {}
    if not PLUGINS_DIR.is_dir():
        return existing
    for path in sorted(PLUGINS_DIR.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(PLUGINS_DIR).as_posix()
        parts = rel.split("/")
        if len(parts) >= 2 and parts[1] in {"skills", ".claude-plugin"}:
            existing[rel] = path.read_text(encoding="utf-8")
        elif rel.endswith("/scripts/grimoire_block.md"):
            existing[rel] = path.read_text(encoding="utf-8")
    return existing


def diff(rendered: dict[str, str], existing: dict[str, str]) -> dict[str, list[str]]:
    return {
        "create": sorted(set(rendered) - set(existing)),
        "update": sorted(k for k in rendered if k in existing and existing[k] != rendered[k]),
        "remove": sorted(set(existing) - set(rendered)),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Render Arcana's command families as Claude Code plugins")
    parser.add_argument("--apply", action="store_true", help="Write the rendered plugin tree (default: report drift)")
    add_output_format_arg(parser)
    args = parser.parse_args()
    human = args.format == "human"

    reporter = ResultReporter("build_plugins", root=ARCANA_PATH, mode="apply" if args.apply else "plan")
    rendered = render_all()
    existing = current_render_targets()
    changes = diff(rendered, existing)
    pending = sum(len(v) for v in changes.values())

    if args.apply:
        for rel in changes["remove"]:
            (PLUGINS_DIR / rel).unlink()
            reporter.mutation("remove", path=PLUGINS_DIR / rel)
        for rel in changes["create"] + changes["update"]:
            target = PLUGINS_DIR / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(rendered[rel].encode("utf-8"))
            reporter.mutation("write", path=target)
        if human:
            print(f"  [OK]    plugins/: {len(changes['create'])} created, {len(changes['update'])} updated, {len(changes['remove'])} removed")
        else:
            reporter.emit(args.format, summary={"version": version(), **{k: len(v) for k, v in changes.items()}})
        return 0

    if pending:
        for action, items in changes.items():
            for rel in items:
                reporter.message("warning", f"would {action} plugins/{rel}", path=PLUGINS_DIR / rel)
        reporter.set_status("blocked")
    else:
        reporter.set_status("noop")
    if human:
        if pending:
            for action, items in changes.items():
                for rel in items:
                    print(f"  [DIFF]  would {action} plugins/{rel}")
            print("  Re-run with --apply to write plugins/.")
        else:
            print("  [OK]    plugins/ is up to date.")
        return 1 if pending else 0
    reporter.emit(args.format, summary={"version": version(), **{k: len(v) for k, v in changes.items()}})
    return 1 if pending else 0


if __name__ == "__main__":
    sys.exit(main())
